def catalog_country_name(code: str) -> str:
    """Return the public country label for a supported Mooble region code."""
    return dict(CATALOG_COUNTRIES).get(code.casefold(), code.upper())


def english_category_name(category_id: str, source_name: str) -> str:
    """Translate one category without leaking source-language fallback words."""
    name = source_name.strip()
    translated = _ENGLISH_BY_ID.get(category_id) or _ENGLISH_BY_NAME.get(name)
    if translated:
        return translated
    if name in _KNOWN_ENGLISH_NAMES:
        return name
    numbered = _NUMBERED_SET.fullmatch(name)
    if numbered:
        return f"Set {numbered.group(1)}"
    if name in _UNCHANGED_NAMES:
        return name
    # Mooble can add region-specific taxonomy without notice. An English-only,
    # stable fallback is preferable to silently mixing languages in one list.
    digest = hashlib.sha1(category_id.encode("utf-8")).hexdigest()[:6].upper()
    return f"Other category [{digest}]"


def category_display_name(
    category_id: str,
    source_name: str,
    language: str,
) -> str:
    """Return either the untouched source label or its English counterpart."""
    if language == CATEGORY_LANGUAGE_ENGLISH:
        return english_category_name(category_id, source_name)
    return source_name
